package osprofileconvert

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"sigs.k8s.io/yaml"

	enginev1 "github.com/dsx-ai-factory/nke/management-engine/apis/v1"
)

const (
	dirMachineImages    = "machineimages"
	dirClusterReleases  = "clusterreleases"
	dirNodePoolReleases = "nodepoolreleases"

	generatedHeader = `# SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.
# SPDX-License-Identifier: Apache-2.0
# Generated by osprofile-convert. Published specs are append-only; only release deprecation state may change.

`
)

var (
	// ErrSpecMutation is returned when regeneration would change a manifest
	// that already exists, other than release deprecation state. The refused
	// content is the machine image spec, the release image reference and user
	// data, and the Kubernetes-version annotations that record
	// fixed-versus-injected compatibility.
	ErrSpecMutation = errors.New("published spec is immutable")

	// ErrDrift is returned in check mode when the output directory is not the
	// current rendering. A deprecation-state change is drift until it is
	// written; it is not a spec mutation.
	ErrDrift = errors.New("generated manifests have drifted")
)

// SyncOptions selects whether Sync writes the catalog or only compares it.
type SyncOptions struct {
	// Check compares the output directory to the catalog and writes nothing.
	Check bool
}

// SyncResult reports how many manifest files Sync wrote.
type SyncResult struct {
	// Written is the number of manifest files created or updated.
	Written int
}

// Manifests renders the catalog to deterministic YAML. Keys are relative
// paths using forward slashes: machineimages/<name>.yaml,
// clusterreleases/<name>.yaml, and nodepoolreleases/<name>.yaml.
func (c Catalog) Manifests() (map[string][]byte, error) {
	out := make(map[string][]byte, len(c.Profiles)*3)
	for _, profile := range c.Profiles {
		image, err := render(profile.MachineImage)
		if err != nil {
			return nil, fmt.Errorf("render machine image %s: %w", profile.Name, err)
		}
		cluster, err := render(profile.ClusterRelease)
		if err != nil {
			return nil, fmt.Errorf("render cluster release %s: %w", profile.Name, err)
		}
		pool, err := render(profile.NodePoolRelease)
		if err != nil {
			return nil, fmt.Errorf("render node pool release %s: %w", profile.Name, err)
		}
		out[manifestKey(dirMachineImages, profile.Name)] = image
		out[manifestKey(dirClusterReleases, profile.Name)] = cluster
		out[manifestKey(dirNodePoolReleases, profile.Name)] = pool
	}
	return out, nil
}

func manifestKey(dir, name string) string {
	return dir + "/" + name + ".yaml"
}

func render(obj any) ([]byte, error) {
	body, err := yaml.Marshal(obj)
	if err != nil {
		return nil, err
	}
	if len(body) == 0 || body[len(body)-1] != '\n' {
		body = append(body, '\n')
	}
	out := make([]byte, 0, len(generatedHeader)+len(body))
	out = append(out, generatedHeader...)
	out = append(out, body...)
	return out, nil
}

// Sync writes the catalog into outputDir, or compares it when opts.Check is
// set. A manifest that already exists may change only its release deprecation
// state. New profiles are appended. Removing a published manifest fails in
// both modes.
func (c Catalog) Sync(outputDir string, opts SyncOptions) (SyncResult, error) {
	if outputDir == "" {
		return SyncResult{}, errors.New("output directory is required")
	}
	want, err := c.Manifests()
	if err != nil {
		return SyncResult{}, err
	}
	have, err := loadPublished(outputDir)
	if err != nil {
		return SyncResult{}, err
	}

	var mutations []string
	var updates []string
	for key := range have {
		if _, ok := want[key]; !ok {
			mutations = append(mutations, fmt.Sprintf("%s: published manifest is not produced from the current profile tree", key))
		}
	}
	for key, body := range want {
		existing, ok := have[key]
		if !ok {
			updates = append(updates, key)
			continue
		}
		if bytes.Equal(existing, body) {
			continue
		}
		changed, err := publishedContentChanged(key, existing, body)
		if err != nil {
			return SyncResult{}, err
		}
		if changed {
			mutations = append(mutations, fmt.Sprintf("%s: published content differs from the profile source", key))
			continue
		}
		updates = append(updates, key)
	}
	sort.Strings(mutations)
	if len(mutations) > 0 {
		return SyncResult{}, fmt.Errorf("%w:\n%s", ErrSpecMutation, strings.Join(mutations, "\n"))
	}
	sort.Strings(updates)
	if opts.Check {
		if len(updates) > 0 {
			return SyncResult{}, fmt.Errorf("%w:\n%s", ErrDrift, strings.Join(updates, "\n"))
		}
		return SyncResult{}, nil
	}
	if err := writeAll(outputDir, updates, want); err != nil {
		return SyncResult{}, err
	}
	return SyncResult{Written: len(updates)}, nil
}

func loadPublished(root string) (map[string][]byte, error) {
	out := map[string][]byte{}
	for _, dir := range []string{dirMachineImages, dirClusterReleases, dirNodePoolReleases} {
		files, err := loadDir(root, dir)
		if err != nil {
			return nil, err
		}
		for key, body := range files {
			out[key] = body
		}
	}
	return out, nil
}

func loadDir(root, kindDir string) (map[string][]byte, error) {
	dir := filepath.Join(root, kindDir)
	entries, err := os.ReadDir(dir)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return map[string][]byte{}, nil
		}
		return nil, fmt.Errorf("read %s: %w", dir, err)
	}
	out := make(map[string][]byte, len(entries))
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".yaml") {
			continue
		}
		path := filepath.Join(dir, entry.Name())
		body, err := os.ReadFile(path)
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", path, err)
		}
		out[kindDir+"/"+entry.Name()] = body
	}
	return out, nil
}

func publishedContentChanged(key string, existing, generated []byte) (bool, error) {
	switch {
	case strings.HasPrefix(key, dirMachineImages+"/"):
		return machineImageChanged(existing, generated)
	case strings.HasPrefix(key, dirClusterReleases+"/"):
		return clusterReleaseChanged(existing, generated)
	case strings.HasPrefix(key, dirNodePoolReleases+"/"):
		return nodePoolReleaseChanged(existing, generated)
	default:
		return false, fmt.Errorf("%s: unknown manifest path", key)
	}
}

func machineImageChanged(existing, generated []byte) (bool, error) {
	var got, want enginev1.MachineImage
	if err := unmarshalPublished(existing, &got); err != nil {
		return false, err
	}
	if err := yaml.Unmarshal(generated, &want); err != nil {
		return false, fmt.Errorf("decode generated machine image: %w", err)
	}
	return got.Name != want.Name || got.APIVersion != want.APIVersion || got.Kind != want.Kind || got.Spec != want.Spec, nil
}

func clusterReleaseChanged(existing, generated []byte) (bool, error) {
	var got, want enginev1.ClusterRelease
	if err := unmarshalPublished(existing, &got); err != nil {
		return false, err
	}
	if err := yaml.Unmarshal(generated, &want); err != nil {
		return false, fmt.Errorf("decode generated cluster release: %w", err)
	}
	return releaseChanged(clusterView(got), clusterView(want)), nil
}

func nodePoolReleaseChanged(existing, generated []byte) (bool, error) {
	var got, want enginev1.NodePoolRelease
	if err := unmarshalPublished(existing, &got); err != nil {
		return false, err
	}
	if err := yaml.Unmarshal(generated, &want); err != nil {
		return false, fmt.Errorf("decode generated node pool release: %w", err)
	}
	return releaseChanged(nodePoolView(got), nodePoolView(want)), nil
}

type releaseView struct {
	name       string
	apiVersion string
	kind       string
	ref        enginev1.MachineImageReference
	init       enginev1.MachineInit
	version    string
	injected   string
}

func clusterView(obj enginev1.ClusterRelease) releaseView {
	return releaseView{
		name: obj.Name, apiVersion: obj.APIVersion, kind: obj.Kind,
		ref: obj.Spec.MachineImageRef, init: obj.Spec.MachineInit,
		version:  obj.Annotations[enginev1.MachineInitKubernetesVersionAnnotation],
		injected: obj.Annotations[enginev1.MachineInitKubernetesVersionInjectedAnnotation],
	}
}

func nodePoolView(obj enginev1.NodePoolRelease) releaseView {
	return releaseView{
		name: obj.Name, apiVersion: obj.APIVersion, kind: obj.Kind,
		ref: obj.Spec.MachineImageRef, init: obj.Spec.MachineInit,
		version:  obj.Annotations[enginev1.MachineInitKubernetesVersionAnnotation],
		injected: obj.Annotations[enginev1.MachineInitKubernetesVersionInjectedAnnotation],
	}
}

func releaseChanged(got, want releaseView) bool {
	return got != want
}

func unmarshalPublished(data []byte, obj any) error {
	if err := yaml.Unmarshal(data, obj); err != nil {
		return fmt.Errorf("%w: cannot read published manifest: %w", ErrSpecMutation, err)
	}
	return nil
}

type stagedFile struct{ tmp, dst string }

func writeAll(root string, keys []string, bodies map[string][]byte) error {
	wrote := make([]stagedFile, 0, len(keys))
	for _, key := range keys {
		dst, tmp, err := stage(root, key, bodies[key])
		if err != nil {
			if cleanErr := removeTemps(wrote); cleanErr != nil {
				return errors.Join(err, cleanErr)
			}
			return err
		}
		wrote = append(wrote, stagedFile{tmp: tmp, dst: dst})
	}
	for i, item := range wrote {
		if err := os.Rename(item.tmp, item.dst); err != nil {
			err = fmt.Errorf("rename %s: %w", item.dst, err)
			if cleanErr := removeTemps(wrote[i:]); cleanErr != nil {
				return errors.Join(err, cleanErr)
			}
			return err
		}
	}
	return nil
}

func stage(root, key string, body []byte) (string, string, error) {
	rel := filepath.FromSlash(key)
	if !filepath.IsLocal(rel) {
		return "", "", fmt.Errorf("manifest path %s escapes the output directory", key)
	}
	dst := filepath.Join(root, rel)
	if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
		return "", "", fmt.Errorf("create directory for %s: %w", dst, err)
	}
	f, err := os.CreateTemp(filepath.Dir(dst), ".osprofile-convert-*")
	if err != nil {
		return "", "", fmt.Errorf("create temp file for %s: %w", dst, err)
	}
	tmp := f.Name()
	if _, err := f.Write(body); err != nil {
		return "", "", closeAndDiscard(f, tmp, fmt.Errorf("write %s: %w", dst, err))
	}
	if err := f.Chmod(0o644); err != nil {
		return "", "", closeAndDiscard(f, tmp, fmt.Errorf("chmod %s: %w", dst, err))
	}
	if err := f.Close(); err != nil {
		return "", "", discardTemp(tmp, fmt.Errorf("close %s: %w", dst, err))
	}
	return dst, tmp, nil
}

func closeAndDiscard(f *os.File, path string, cause error) error {
	if err := f.Close(); err != nil {
		cause = fmt.Errorf("%w (also closing temp file: %v)", cause, err)
	}
	return discardTemp(path, cause)
}

func discardTemp(path string, cause error) error {
	if err := os.Remove(path); err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("%w (also removing temp file: %v)", cause, err)
	}
	return cause
}

func removeTemps(paths []stagedFile) error {
	var errs []error
	for _, item := range paths {
		if err := os.Remove(item.tmp); err != nil && !errors.Is(err, os.ErrNotExist) {
			errs = append(errs, err)
		}
	}
	return errors.Join(errs...)
}
